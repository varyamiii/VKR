    CONSTRAINT chk_accents_name_en_not_blank
        CHECK (btrim(name_en) <> ''),
    CONSTRAINT chk_accents_tts_language_code_not_blank
        CHECK (btrim(tts_language_code) <> '')
);

DROP TRIGGER IF EXISTS trg_accents_set_updated_at ON app.accents;
CREATE TRIGGER trg_accents_set_updated_at
