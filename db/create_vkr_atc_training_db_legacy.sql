-- ------------------------------------------------------------
-- 1. Создание базы данных
-- ------------------------------------------------------------
-- Команду CREATE DATABASE нужно выполнять, подключившись к служебной БД,
-- например postgres. Если база уже создана, этот блок можно пропустить.

-- CREATE DATABASE vkr_atc_training
--     WITH
--     ENCODING = 'UTF8'
--     TEMPLATE = template0;

-- После создания базы подключитесь к ней:
-- \connect vkr_atc_training

-- ------------------------------------------------------------
-- 2. Схема приложения
-- ------------------------------------------------------------

CREATE SCHEMA IF NOT EXISTS app;
SET search_path TO app, public;

-- ------------------------------------------------------------
-- 3. Перечислимые типы
-- ------------------------------------------------------------

DO $$
BEGIN
    CREATE TYPE app.phrase_role AS ENUM ('pilot', 'controller', 'both');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
    CREATE TYPE app.difficulty_level AS ENUM ('basic', 'intermediate', 'advanced');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
    CREATE TYPE app.noise_type AS ENUM ('none', 'file', 'generated');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
    CREATE TYPE app.generation_status AS ENUM ('processing', 'success', 'failed');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
    CREATE TYPE app.test_type AS ENUM ('choice', 'manual_input');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- ------------------------------------------------------------
-- 4. Служебная функция обновления updated_at
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION app.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------
-- 5. Справочник категорий фраз
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS app.phrase_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL UNIQUE,
    name_ru     VARCHAR(255) NOT NULL,
    name_en     VARCHAR(255) NOT NULL,
    description TEXT,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_phrase_categories_code_not_blank
        CHECK (btrim(code) <> ''),
    CONSTRAINT chk_phrase_categories_name_ru_not_blank
        CHECK (btrim(name_ru) <> ''),
    CONSTRAINT chk_phrase_categories_name_en_not_blank
        CHECK (btrim(name_en) <> '')
);

DROP TRIGGER IF EXISTS trg_phrase_categories_set_updated_at ON app.phrase_categories;
CREATE TRIGGER trg_phrase_categories_set_updated_at
BEFORE UPDATE ON app.phrase_categories
FOR EACH ROW
EXECUTE FUNCTION app.set_updated_at();

-- ------------------------------------------------------------
-- 6. Учебные авиационные фразы
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS app.aviation_phrases (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id      BIGINT NOT NULL,
    phrase_text      TEXT NOT NULL,
    phrase_template  TEXT,
    example_text     TEXT,
    role             app.phrase_role NOT NULL DEFAULT 'both',
    difficulty_level app.difficulty_level NOT NULL DEFAULT 'basic',
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_aviation_phrases_category
        FOREIGN KEY (category_id)
        REFERENCES app.phrase_categories (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_aviation_phrases_phrase_text_not_blank
        CHECK (btrim(phrase_text) <> ''),

    CONSTRAINT uq_aviation_phrases_category_phrase
        UNIQUE (category_id, phrase_text)
);

DROP TRIGGER IF EXISTS trg_aviation_phrases_set_updated_at ON app.aviation_phrases;
CREATE TRIGGER trg_aviation_phrases_set_updated_at
BEFORE UPDATE ON app.aviation_phrases
FOR EACH ROW
EXECUTE FUNCTION app.set_updated_at();

-- ------------------------------------------------------------
